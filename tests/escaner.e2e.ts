import assert from "node:assert/strict";
import type { APIRequestContext, Page, Request as Peticion } from "playwright";
import type { RevisionFactura } from "@/lib/escaner/tipos";
export async function probar_escaner(pagina: Page, origen: string, admin: APIRequestContext) {
  await pagina.goto(`${origen}/escaner`);
  assert.equal(await pagina.getByLabel("Foto para escanear", { exact: true }).getAttribute("capture"), "environment");
  const imagen = await pagina.evaluate(() => {
    const canvas = document.createElement("canvas"); canvas.width = 4000; canvas.height = 3000;
    const contexto = canvas.getContext("2d")!; contexto.fillStyle = "white"; contexto.fillRect(0, 0, 4000, 3000); contexto.fillStyle = "black"; contexto.font = "90px sans-serif"; contexto.fillText("Factura de prueba", 120, 120);
    return canvas.toDataURL("image/jpeg", 0.95).split(",")[1];
  });
  let registros = 0;
  function contar(peticion: Peticion) { if (peticion.url().endsWith("/guias/nueva/api/registrar")) registros++; }
  pagina.on("request", contar);
  await pagina.getByLabel("Foto para escanear", { exact: true }).setInputFiles({ name: "factura.jpg", mimeType: "image/jpeg", buffer: Buffer.from(imagen, "base64") });
  const preview = pagina.getByAltText("Vista previa de la factura", { exact: true }); await preview.waitFor();
  assert.equal(await preview.evaluate(async (nodo) => { const imagen = nodo as HTMLImageElement; await imagen.decode(); return imagen.naturalWidth; }), 1600);
  await pagina.screenshot({ path: "test-results/escaner-preview.png", fullPage: true });
  const respuesta_ocr = pagina.waitForResponse((respuesta) => respuesta.url().endsWith("/api/escaner"));
  await pagina.getByRole("button", { name: "Analizar factura", exact: true }).click();
  const respuesta = await respuesta_ocr; if (respuesta.status() !== 200) throw new Error(`OCR fallo (${respuesta.status()}): ${(await respuesta.json()).error}`);
  const revision = await respuesta.json() as RevisionFactura;
  assert(revision.demostracion); assert.equal(registros, 0);
  await pagina.getByRole("heading", { name: "Revisa y confirma la factura", exact: true }).waitFor();
  const guardar = pagina.getByRole("button", { name: "Confirmar y guardar entrada", exact: true });
  assert(await guardar.isDisabled());
  assert.equal(await pagina.getByLabel("Producto ítem 1", { exact: true }).inputValue(), "Aceite vegetal");
  assert.equal(await pagina.getByLabel("Producto ítem 2", { exact: true }).inputValue(), "Arroz");
  const primero = revision.items[0].producto!;
  const saldo = await (await pagina.request.get(`${origen}/guias/nueva/api/productos?producto_id=${primero.id}`)).json();
  assert.equal(saldo.filas[0].stock_1, primero.stock_1, "OCR no modifica stock.");
  const datos = { tipo: "entrada", fecha: revision.factura.fecha, bodega_ajuste: 1, n_factura: "E2E-OCR", glosa: "", items: revision.items.filter((item) => item.producto).map((item) => ({ producto_id: item.producto!.id, cantidad: String(item.cantidad), marca: "", descripcion: item.descripcion })) };
  const sin_confirmar = await pagina.request.post(`${origen}/guias/nueva/api/registrar`, { headers: { Origin: origen }, multipart: { escaneo: revision.token, datos: JSON.stringify(datos) } });
  assert.equal(sin_confirmar.status(), 400);
  assert.equal((await admin.get(revision.imagen_url)).status(), 404, "Admin no accede a borradores ajenos.");
  assert.equal((await admin.post(`${origen}/api/escaner`, { headers: { Origin: origen }, multipart: {} })).status(), 403);
  assert.equal((await pagina.request.get(`${origen}/uploads/${new URL(revision.imagen_url).pathname.split("/").slice(-2).join("/")}`)).status(), 404);
  await pagina.getByLabel("Número de factura", { exact: true }).fill("E2E-OCR-REV");
  await pagina.getByLabel("Proveedor", { exact: true }).fill("Proveedor revisado");
  await pagina.getByLabel("Confirmo que revisé la factura", { exact: true }).check();
  await pagina.getByRole("button", { name: "Crear producto ítem 3", exact: true }).click();
  const modal = pagina.getByRole("dialog", { name: "Nuevo Producto", exact: true });
  await modal.getByLabel("Nombre", { exact: true }).fill("Producto OCR revisado");
  await modal.getByLabel("Categoría", { exact: true }).selectOption("1");
  await modal.getByRole("button", { name: "Guardar Producto", exact: true }).click();
  await pagina.getByLabel("Producto ítem 3", { exact: true }).waitFor();
  await pagina.waitForFunction(() => (document.querySelector('[aria-label="Producto ítem 3"]') as HTMLInputElement)?.value === "Producto OCR revisado");
  await pagina.waitForFunction(() => (document.querySelector('[aria-label="Unidad ítem 3"]') as HTMLInputElement)?.value === "un");
  assert.equal(registros, 0, "Crear ficha no envia el formulario de entrada.");
  assert.equal(await pagina.getByLabel("Confirmo que revisé la factura", { exact: true }).isChecked(), false);
  await pagina.getByLabel("Confirmo que revisé la factura", { exact: true }).check();
  await pagina.screenshot({ path: "test-results/escaner-confirmacion.png", fullPage: true });
  await guardar.click();
  await pagina.getByRole("status").filter({ hasText: "Guía registrada:" }).waitFor();
  assert.equal(registros, 1);
  const folio = (await pagina.getByRole("heading", { name: /^Guía G1-/ }).innerText()).replace("Guía ", "");
  const guia = await (await pagina.request.get(`${origen}/guias/nueva/api/guias/${folio}`)).json();
  assert.equal(guia.n_factura, "E2E-OCR-REV"); assert.equal(guia.items.length, 3);
  assert.equal(guia.imagen_factura_url, revision.imagen_url); assert.equal(guia.glosa, "Proveedor: Proveedor revisado");
  assert.equal((await admin.get(revision.imagen_url)).status(), 200);
  const saldo_nuevo = await (await pagina.request.get(`${origen}/guias/nueva/api/productos?producto_id=${primero.id}`)).json();
  assert.equal(Number(saldo_nuevo.filas[0].stock_1), Number(primero.stock_1) + 2.5);
  await pagina.getByRole("link", { name: "Hacer traspaso a Bodega 2", exact: true }).click();
  await pagina.waitForURL((url) => url.pathname === "/guias/nueva" && url.searchParams.get("desde") === folio);
  assert.equal(await pagina.getByLabel("Tipo de guía", { exact: true }).inputValue(), "traspaso");
  assert.equal(await pagina.getByLabel("Cantidad ítem 1", { exact: true }).inputValue(), "2.500");
  assert.equal(await pagina.getByLabel("Producto ítem 3", { exact: true }).inputValue(), "Producto OCR revisado");
  assert.equal(await pagina.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
  pagina.off("request", contar);
  console.info("OK: escaner movil, compresion JPEG a 1600px, OCR mock, sin registro automatico, confirmacion obligatoria, alta de ficha, entrada y traspaso prellenado.");
}
