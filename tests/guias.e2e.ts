import assert from "node:assert/strict";
import { join } from "node:path";
import type { Page } from "playwright";
import { leer_filtros_historial } from "@/lib/guias/tipos";
export async function probar_guias(pagina: Page, origen: string) {
  await pagina.goto(`${origen}/guias/nueva?tipo=entrada`);
  await pagina.getByRole("heading", { name: "Nueva guía", exact: true }).waitFor();
  await pagina.getByLabel("Número de factura", { exact: true }).fill("E2E-FAC-001");
  await pagina.getByLabel("Producto ítem 1", { exact: true }).fill("Aceite vegetal");
  await pagina.getByRole("option").filter({ hasText: "Aceite vegetal" }).first().click();
  assert.equal(await pagina.getByLabel("Unidad ítem 1", { exact: true }).inputValue(), "lt");
  await pagina.getByLabel("Cantidad ítem 1", { exact: true }).fill("2.500");
  await pagina.getByLabel("Marca ítem 1", { exact: true }).fill("Marca de prueba");
  await pagina.getByLabel("Descripción ítem 1", { exact: true }).fill("Reposición de prueba");
  await pagina.getByLabel("Foto de factura (opcional)").setInputFiles(join(process.cwd(), "public/img/hotel.jpg"));
  await pagina.getByRole("button", { name: "Guardar guía", exact: true }).click();
  await pagina.getByRole("status").filter({ hasText: "Guía registrada:" }).waitFor();
  const titulo = await pagina.getByRole("heading", { name: /^Guía G1-/ }).innerText();
  const folio = titulo.replace("Guía ", "");
  await pagina.getByAltText(`Factura de la guía ${folio}`, { exact: true }).waitFor();
  const imagen = await pagina.getByAltText(`Factura de la guía ${folio}`, { exact: true }).getAttribute("src");
  assert(imagen);
  assert.equal((await pagina.request.get(imagen)).status(), 200);
  const recibo = await (await pagina.request.get(`${origen}/guias/nueva/api/guias/${folio}`)).json();
  assert.equal(recibo.items[0].cantidad, "2.500"); assert.equal(recibo.items[0].marca, "Marca de prueba");
  await pagina.emulateMedia({ media: "print" });
  assert.equal(await pagina.getByRole("button", { name: "Imprimir guía", exact: true }).isVisible(), false);
  assert(await pagina.getByRole("heading", { name: `Guía ${folio}`, exact: true }).isVisible());
  await pagina.pdf({ path: "test-results/guia-impresion.pdf", format: "A4" });
  await pagina.emulateMedia({ media: "screen" });
  await pagina.goto(`${origen}/historial?folio=${folio}`);
  await pagina.getByRole("heading", { name: "Historial General de Movimientos", exact: true }).waitFor();
  assert.equal(await pagina.locator("tbody tr").count(), 1);
  await pagina.getByRole("link", { name: `Ver guía ${folio}`, exact: true }).click();
  await pagina.getByRole("heading", { name: `Guía ${folio}`, exact: true }).waitFor();
  assert(await pagina.getByText("E2E-FAC-001", { exact: true }).isVisible());
  await pagina.screenshot({ path: "test-results/guia-detalle.png", fullPage: true });
  await pagina.goto(`${origen}/historial`);
  await pagina.getByLabel("Buscar por Folio", { exact: true }).fill("no-existe-xyz");
  await pagina.getByRole("button", { name: "Buscar", exact: true }).click();
  await pagina.getByText("No se encontraron movimientos", { exact: true }).waitFor();
  await pagina.screenshot({ path: "test-results/historial-vacio.png" });
  await pagina.getByLabel("Buscar por Folio", { exact: true }).fill("E2E-FAC-001");
  await pagina.getByLabel("Tipo de historial", { exact: true }).selectOption("entrada");
  await pagina.getByRole("button", { name: "Buscar", exact: true }).click();
  await pagina.getByRole("link", { name: `Ver guía ${folio}`, exact: true }).waitFor();
  const descarga = pagina.waitForEvent("download"); await pagina.getByRole("link", { name: "Exportar Lista", exact: true }).click();
  assert.equal((await descarga).suggestedFilename(), "historial-guias.xlsx");
  await pagina.getByLabel("Fecha Inicio", { exact: true }).fill("2026-10-15");
  await pagina.getByLabel("Fecha Fin", { exact: true }).fill("2026-10-13");
  await pagina.getByRole("button", { name: "Buscar", exact: true }).click();
  await pagina.getByRole("alert").filter({ hasText: "Revisa los filtros" }).waitFor();
  assert(leer_filtros_historial({ inicio: "2026-10-15", fin: "2026-10-13" }).aviso);
  await pagina.goto(`${origen}/guias/nueva?tipo=traspaso`);
  assert.equal(await pagina.getByLabel("Tipo de guía", { exact: true }).inputValue(), "traspaso");
  await pagina.getByLabel("Producto ítem 1", { exact: true }).fill("Aceite vegetal");
  await pagina.getByRole("option").filter({ hasText: "Aceite vegetal" }).first().click();
  await pagina.getByLabel("Cantidad ítem 1", { exact: true }).fill("999999999");
  let registros = 0;
  pagina.on("request", contar_registro);
  function contar_registro(request: { url: () => string }) { if (request.url().endsWith("/guias/nueva/api/registrar")) registros++; }
  await pagina.getByRole("button", { name: "Guardar guía", exact: true }).click();
  await pagina.getByRole("alert").filter({ hasText: "Stock insuficiente: Aceite vegetal" }).waitFor();
  assert.equal(registros, 0, "El formulario rechaza el exceso antes de enviar la guia.");
  pagina.off("request", contar_registro);
  await pagina.setViewportSize({ width: 390, height: 844 });
  assert.equal(await pagina.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
  await pagina.evaluate(() => window.scrollTo(0, 0));
  await pagina.screenshot({ path: "test-results/guia-movil.png", fullPage: true });
  await pagina.setViewportSize({ width: 1366, height: 768 });
  console.info("OK: guia compra, factura privada, detalle inmutable, impresion PDF, historial/Excel/filtros, validacion de stock en formulario y movil.");
  return { folio, imagen };
}

export async function probar_guias_trabajador(pagina: Page, origen: string, factura_ajena: string, folio_ajeno: string) {
  await pagina.goto(`${origen}/guias/nueva?tipo=traspaso`);
  assert.equal(await pagina.getByLabel("Tipo de guía", { exact: true }).locator('option[value="ajuste_positivo"]').count(), 0);
  assert.equal((await pagina.request.get(factura_ajena)).status(), 404);
  assert.equal((await pagina.request.get(`${origen}/guias/nueva/api/guias/${folio_ajeno}`)).status(), 404);
  await pagina.getByLabel("Producto ítem 1", { exact: true }).fill("Aceite vegetal");
  await pagina.getByRole("option").filter({ hasText: "Aceite vegetal" }).first().click();
  await pagina.getByLabel("Cantidad ítem 1", { exact: true }).fill("0.125");
  await pagina.getByRole("button", { name: "Guardar guía", exact: true }).click();
  await pagina.getByRole("status").filter({ hasText: "Guía registrada:" }).waitFor();
  assert(await pagina.getByRole("button", { name: "Imprimir guía", exact: true }).isVisible());
  const ajuste = { tipo: "ajuste_positivo", fecha: "2026-10-14", bodega_ajuste: 1, n_factura: "", glosa: "", items: [{ producto_id: 1, cantidad: "1", marca: "", descripcion: "" }] };
  assert.equal((await pagina.request.post(`${origen}/guias/nueva/api/registrar`, { headers: { Origin: origen }, multipart: { datos: JSON.stringify(ajuste) } })).status(), 403);
  await pagina.goto(`${origen}/historial`);
  assert.equal(new URL(pagina.url()).pathname, "/guias/nueva");
  console.info("OK: trabajador registra e imprime traspaso, sin ajustes ni acceso al historial/facturas ajenas.");
}
