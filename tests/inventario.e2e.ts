import assert from "node:assert/strict";
import ExcelJS from "exceljs";
import type { Page } from "playwright";
import type { PaginaInventario } from "@/lib/inventario/tipos";

export async function probar_inventario(pagina: Page, origen: string) {
  await pagina.goto(`${origen}/inventario`);
  await pagina.getByRole("heading", { name: "Gestión de Inventario", exact: true }).waitFor();
  assert.equal(await pagina.locator("tbody tr").count(), 25);
  assert.equal(await pagina.getByRole("columnheader", { name: "Stock Bodega 1", exact: true }).count(), 1);
  assert.equal(await pagina.getByRole("columnheader", { name: "Stock Bodega 2", exact: true }).count(), 1);
  await pagina.screenshot({ path: "test-results/inventario-escritorio.png" });
  const descarga = pagina.waitForEvent("download");
  await pagina.getByRole("link", { name: "Exportar Excel", exact: true }).click();
  assert((await descarga).suggestedFilename().startsWith("inventario-global-"));
  const archivo = await pagina.request.get(`${origen}/api/inventario/exportar`);
  assert.equal(archivo.status(), 200);
  const libro = new ExcelJS.Workbook(); await libro.xlsx.load(await archivo.body() as unknown as ExcelJS.Buffer);
  assert.equal(libro.worksheets[0].rowCount, 61, "Excel incluye las 60 filas, no solo la pagina visible.");
  await pagina.getByLabel("Registros por página", { exact: true }).selectOption("10");
  await pagina.waitForURL((url) => url.searchParams.get("registros") === "10");
  await pagina.getByText("Mostrando 1–10 de 60 productos", { exact: true }).waitFor();
  assert.equal(await pagina.locator("tbody tr").count(), 10);
  const primera_fila = await pagina.locator("tbody tr").first().innerText();
  await pagina.getByRole("link", { name: "Siguiente →", exact: true }).click();
  await pagina.getByText("Mostrando 11–20 de 60 productos", { exact: true }).waitFor();
  assert.notEqual(await pagina.locator("tbody tr").first().innerText(), primera_fila);
  await pagina.getByLabel("Vista actual", { exact: true }).selectOption("2");
  await pagina.waitForURL((url) => url.searchParams.get("bodega") === "2" && url.searchParams.get("pagina") === "1");
  await pagina.getByRole("columnheader", { name: "Stock Bodega 2", exact: true }).waitFor();
  assert.equal(await pagina.getByRole("columnheader", { name: "Stock Bodega 1", exact: true }).count(), 0);
  await pagina.getByLabel("Buscar inventario", { exact: true }).fill("producto que no existe");
  await pagina.getByRole("button", { name: "Buscar en inventario", exact: true }).click();
  await pagina.getByText("No hay productos que coincidan con los filtros.", { exact: true }).waitFor();

  await pagina.goto(`${origen}/inventario`);
  const catalogo = await (await pagina.request.get(`${origen}/api/inventario/productos?registros=100`)).json() as PaginaInventario;
  const producto = catalogo.filas.find((producto) => Number(producto.stock_1) > 1)!;
  assert(producto);
  await pagina.getByLabel("Producto para traspaso", { exact: true }).fill(producto.nombre);
  const selector = pagina.getByLabel("Producto para traspaso", { exact: true });
  await pagina.getByRole("option").filter({ hasText: producto.nombre }).first().waitFor();
  await selector.press("ArrowDown");
  await selector.press("Enter");
  await pagina.getByLabel("Cantidad del traspaso", { exact: true }).fill("0.125");
  await pagina.getByRole("button", { name: "Enviar traspaso", exact: true }).click();
  await pagina.getByRole("status").filter({ hasText: "Traspaso registrado:" }).waitFor();
  const detalle = await (await pagina.request.get(`${origen}/api/inventario/productos/${producto.id}`)).json();
  assert.equal(Number(detalle.producto.stock_1), Number(producto.stock_1) - 0.125);
  assert.equal(Number(detalle.producto.stock_2), Number(producto.stock_2) + 0.125);
  assert.equal(detalle.movimientos[0].tipo, "traspaso");
  assert.equal(detalle.movimientos[0].folio, detalle.movimientos[1].folio);
  await pagina.getByLabel("Cantidad del traspaso", { exact: true }).fill("999999999");
  await pagina.getByRole("button", { name: "Enviar traspaso", exact: true }).click();
  await pagina.getByRole("alert").filter({ hasText: "Stock insuficiente en Bodega 1" }).waitFor();
  const despues = await (await pagina.request.get(`${origen}/api/inventario/productos/${producto.id}`)).json();
  assert.deepEqual(despues, detalle, "El rechazo no modifica saldos ni historial.");
  assert.equal((await pagina.request.post(`${origen}/api/inventario/traspasos`, { headers: { Origin: "https://otro-sitio.cl" }, data: {} })).status(), 403);

  await pagina.getByRole("button", { name: "Nuevo Producto", exact: true }).click();
  const modal = pagina.getByRole("dialog", { name: "Nuevo Producto", exact: true });
  await modal.getByLabel("Nombre", { exact: true }).fill("Producto prueba inventario");
  await modal.getByLabel("Categoría", { exact: true }).selectOption("1");
  await modal.getByLabel("Crítico", { exact: true }).fill("5");
  await modal.getByRole("button", { name: "Guardar Producto", exact: true }).click();
  await modal.getByRole("alert").filter({ hasText: "Los niveles deben cumplir" }).waitFor();
  await modal.getByLabel("Mínimo", { exact: true }).fill("10");
  await modal.getByLabel("Máximo", { exact: true }).fill("100");
  await modal.getByLabel("Costo (CLP)", { exact: true }).fill("1200.50");
  await modal.getByRole("button", { name: "Guardar Producto", exact: true }).click();
  await pagina.getByRole("status").filter({ hasText: "Producto creado:" }).waitFor();
  await pagina.getByRole("button", { name: "Ver Producto prueba inventario", exact: true }).click();
  const drawer = pagina.getByRole("dialog", { name: "Detalle del producto", exact: true });
  await drawer.getByRole("heading", { name: "Producto prueba inventario", exact: true }).waitFor();
  assert.equal(await drawer.getByText("0 kg", { exact: true }).count(), 2);
  await drawer.getByText("Este producto no tiene movimientos hasta esta fecha.", { exact: true }).waitFor();
  await pagina.screenshot({ path: "test-results/inventario-detalle.png" });
  await pagina.keyboard.press("Escape");
  assert.equal(await drawer.count(), 0);
  await pagina.getByLabel("Más acciones de Producto prueba inventario", { exact: true }).click();
  await pagina.getByRole("button", { name: "Consultar Bodega 2", exact: true }).click();
  await pagina.waitForURL((url) => url.searchParams.get("bodega") === "2");
  await pagina.setViewportSize({ width: 390, height: 844 });
  assert.equal(await pagina.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false, "Inventario movil sin desbordamiento global.");
  await pagina.screenshot({ path: "test-results/inventario-movil.png", fullPage: true });
  await pagina.setViewportSize({ width: 1366, height: 768 });
  console.info("OK: inventario, paginacion SQL, busqueda, vistas, Excel completo, traspaso atomico, rechazo sin cambios, alta, drawer, menu y movil.");
}

export async function probar_inventario_admin(pagina: Page, origen: string) {
  await pagina.goto(`${origen}/inventario`);
  await pagina.getByRole("heading", { name: "Gestión de Inventario", exact: true }).waitFor();
  assert.equal(await pagina.getByRole("button", { name: "Nuevo Producto", exact: true }).count(), 0);
  assert.equal(await pagina.getByRole("button", { name: "Enviar traspaso", exact: true }).count(), 0);
  for (const ruta of ["productos", "traspasos"]) assert.equal((await pagina.request.post(`${origen}/api/inventario/${ruta}`, { headers: { Origin: origen }, data: {} })).status(), 403);
  assert.equal((await pagina.request.get(`${origen}/api/inventario/exportar?bodega=2`)).status(), 200);
  await pagina.getByRole("button", { name: /^Ver / }).first().click();
  await pagina.getByRole("dialog", { name: "Detalle del producto" }).getByRole("heading", { name: "Últimos movimientos", exact: true }).waitFor();
  await pagina.keyboard.press("Escape");
  console.info("OK: inventario admin solo lectura en UI y API; detalle y Excel permitidos.");
}
