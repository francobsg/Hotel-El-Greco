import assert from "node:assert/strict";
import { join } from "node:path";
import type { Page } from "playwright";

export async function probar_caja(pagina: Page, admin: Page, origen: string) {
  await pagina.goto(`${origen}/caja`);
  await pagina.getByRole("heading", { name: "Modo caja", exact: true }).waitFor();
  const datos = await (await pagina.request.get(`${origen}/caja/api/datos`)).json();
  const plato = datos.menu.find((p: { nombre: string }) => p.nombre === "Pollo con arroz");
  assert(plato?.disponible >= 3, "El seed de prueba debe tener ingredientes para la venta.");
  let confirmaciones = 0;
  pagina.on("request", (request) => { if (request.url().endsWith("/caja/api/venta") && request.method() === "POST") confirmaciones++; });
  await pagina.getByRole("button", { name: "Agregar Pollo con arroz", exact: true }).click();
  await pagina.getByRole("button", { name: "Agregar Pollo con arroz", exact: true }).click();
  await pagina.getByRole("button", { name: "Quitar Pollo con arroz", exact: true }).click();
  assert.equal(confirmaciones, 0);
  assert.equal(await pagina.getByLabel("Cantidad de Pollo con arroz", { exact: true }).innerText(), "1");
  await pagina.getByRole("button", { name: "Revisar venta", exact: true }).click();
  const revision = pagina.getByRole("dialog", { name: "Confirmar venta provisional", exact: true });
  await revision.waitFor(); assert.equal(confirmaciones, 0);
  const guardar = pagina.waitForResponse((r) => r.url().endsWith("/caja/api/venta") && r.request().method() === "POST");
  await revision.getByRole("button", { name: "Confirmar venta", exact: true }).click();
  const respuesta = await guardar; assert.equal(respuesta.status(), 201);
  const venta = await respuesta.json(); assert.equal(venta.provisional, true);
  await pagina.getByRole("status").filter({ hasText: "Venta confirmada" }).waitFor();
  const recibo = await (await pagina.request.get(`${origen}/guias/nueva/api/guias/${venta.folio}`)).json();
  assert.equal(recibo.provisional, true); assert.equal(recibo.tipo, "venta");
  assert.equal(recibo.origen, "Bodega 2 (Cocina)");
  await pagina.getByRole("region", { name: "Ventas temporales del día", exact: true }).getByText(venta.folio, { exact: true }).waitFor();
  const antes = (await (await pagina.request.get(`${origen}/caja/api/datos`)).json()).resumen.platos.reduce((n: number, p: { cantidad: number }) => n + p.cantidad, 0);
  const lectura = pagina.waitForResponse((r) => r.url().endsWith("/caja/api/boleta"));
  await pagina.getByLabel("Foto de boleta", { exact: true }).setInputFiles(join(process.cwd(), "public/img/hotel.jpg"));
  const leida = await lectura; assert.equal(leida.status(), 200);
  const boleta = pagina.getByRole("dialog", { name: "Revisar boleta", exact: true });
  await boleta.getByText(/Modo demostración/).waitFor();
  assert.equal(await boleta.getByLabel("Cantidad de boleta 1", { exact: true }).inputValue(), "2");
  await boleta.getByLabel("Cantidad de boleta 1", { exact: true }).fill("1");
  await boleta.getByRole("button", { name: "Aplicar al pedido", exact: true }).click();
  assert.equal(confirmaciones, 1, "Escanear/aplicar boleta nunca registra la venta.");
  const despues = (await (await pagina.request.get(`${origen}/caja/api/datos`)).json()).resumen.platos.reduce((n: number, p: { cantidad: number }) => n + p.cantidad, 0);
  assert.equal(despues, antes);
  await pagina.getByRole("button", { name: "Revisar venta", exact: true }).click();
  const guardar_boleta = pagina.waitForResponse((r) => r.url().endsWith("/caja/api/venta"));
  await revision.getByRole("button", { name: "Confirmar venta", exact: true }).click();
  assert.equal((await guardar_boleta).status(), 201);
  await pagina.getByRole("status").filter({ hasText: "Venta confirmada" }).waitFor();
  assert.equal(await pagina.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
  await pagina.screenshot({ path: "test-results/caja-movil.png", fullPage: true });
  assert.equal((await admin.request.get(`${origen}/caja/api/datos`)).status(), 403);
  assert.equal((await admin.request.post(`${origen}/caja/api/venta`, { headers: { Origin: origen }, data: {} })).status(), 403);
  assert.equal((await admin.request.post(`${origen}/caja/api/boleta`, { headers: { Origin: origen }, data: {} })).status(), 403);
  await admin.goto(`${origen}/ventas-diarias`);
  await admin.getByRole("heading", { name: "Ventas diarias", exact: true }).waitFor();
  assert(await admin.getByRole("button", { name: "Subir archivo · Próximamente", exact: true }).isDisabled());
  assert.equal(await admin.locator('input[type="file"]').count(), 0);
  assert(await admin.getByRole("link", { name: "Ventas diarias En desarrollo", exact: true }).isVisible());
  const tabla = admin.getByRole("region", { name: "Días de ventas provisionales", exact: true });
  assert(await tabla.getByText("Pendiente", { exact: true }).first().isVisible());
  assert.equal(await tabla.getByText("Conciliado", { exact: true }).count(), 0);
  const botones = tabla.getByRole("button", { name: "Subir resumen", exact: true });
  for (let i = 0; i < await botones.count(); i++) assert(await botones.nth(i).isDisabled());
  await admin.screenshot({ path: "test-results/ventas-diarias-escritorio.png", fullPage: true });
  await pagina.goto(`${origen}/ventas-diarias`);
  assert.equal(new URL(pagina.url()).pathname, "/escaner");
  console.info("OK: caja móvil, venta provisional, ingredientes, boleta con revisión humana, admin sin mutaciones y Ventas diarias deshabilitado.");
}
